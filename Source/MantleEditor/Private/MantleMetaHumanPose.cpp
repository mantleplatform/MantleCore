{
	static const TArray<FName> Required = { FName(TEXT("Spine")), FName(TEXT("LeftArm")), FName(TEXT("RightArm")), FName(TEXT("LeftLeg")), FName(TEXT("RightLeg")) };
	return Required;
}

FMantlePoseCheck FMantleMetaHumanPose::ComparePose(const TMap<FName, TArray<FVector>>& Body, const TMap<FName, TArray<FVector>>& Template)
{
	using namespace MantleMetaHumanPosePrivate;
	FMantlePoseCheck Out;
	for (const FName& Required : RequiredChains())
	{
		const TArray<FVector>* BodyChain = Body.Find(Required);
		const TArray<FVector>* TemplateChain = Template.Find(Required);
		if (!BodyChain || BodyChain->Num() == 0)
		{
			Out.MissingOnBody.Add(Required);
		}
		if (!TemplateChain || TemplateChain->Num() == 0)
		{
			Out.MissingOnTemplate.Add(Required);
		}
	}
	auto Add = [&Out](const FString& Label, const double Degrees, const bool bJudged)
	{
		if (bJudged && (!Out.Angles.IsValidIndex(Out.Worst) || Degrees > Out.Angles[Out.Worst].Degrees))
		{
			Out.Worst = Out.Angles.Num();
		}
		FMantlePoseAngle& Angle = Out.Angles.AddDefaulted_GetRef();
		Angle.Label = Label;
		Angle.Degrees = Degrees;
		Angle.bJudged = bJudged;
	};
	auto Compare = [&Add](const FString& Label, const FVector& BodyDirection, const FVector& TemplateDirection, const bool bJudged = true)
	{
		if (!BodyDirection.IsNearlyZero() && !TemplateDirection.IsNearlyZero())
		{
			Add(Label, PoseDegrees(BodyDirection, TemplateDirection), bJudged);
		}
	};
	const FName Spine(TEXT("Spine"));
	const FName Neck(TEXT("Neck"));
	const FName Head(TEXT("Head"));
	Compare(TEXT("Spine"), PoseChord(Body, Spine, Neck), PoseChord(Template, Spine, Neck));
	Compare(TEXT("Neck"), PoseChord(Body, Neck, Head), PoseChord(Template, Neck, Head));
	const TCHAR* const Sides[] = { TEXT("Left"), TEXT("Right") };
	for (const TCHAR* const Side : Sides)
	{
		const FName Arm(*FString::Printf(TEXT("%sArm"), Side));
		const TArray<FVector>* BodyArm = Body.Find(Arm);
		const TArray<FVector>* TemplateArm = Template.Find(Arm);
		if (BodyArm && TemplateArm && BodyArm->Num() > 0 && TemplateArm->Num() > 0)
		{
			// A quarter and three quarters along the chain: in the upper arm and in the forearm, twist joints or not.
			const FVector BodyUpper = PoseDirectionAt(*BodyArm, 0.25);
			const FVector BodyFore = PoseDirectionAt(*BodyArm, 0.75);
			const FVector TemplateUpper = PoseDirectionAt(*TemplateArm, 0.25);
			const FVector TemplateFore = PoseDirectionAt(*TemplateArm, 0.75);
			Compare(Arm.ToString() + TEXT(" upper arm"), BodyUpper, TemplateUpper);
			Compare(Arm.ToString() + TEXT(" forearm"), BodyFore, TemplateFore);
			if (!BodyUpper.IsNearlyZero() && !BodyFore.IsNearlyZero() && !TemplateUpper.IsNearlyZero() && !TemplateFore.IsNearlyZero())
			{
				Add(Arm.ToString() + TEXT(" elbow bend"), FMath::Abs(PoseDegrees(BodyUpper, BodyFore) - PoseDegrees(TemplateUpper, TemplateFore)), true);
			}
			// The hand: the arm's end to the first joint of the side's middle finger, the knuckle. Reported, not judged: it
			// follows the hand's anatomy (where the knuckles sit), not the pose, and the conform's hand re-estimate redoes every hand
			// and finger joint (the build's finger-joint bar covers the hand).
			const FName Middle(*FString::Printf(TEXT("%sMiddle"), Side));
			const TArray<FVector>* BodyMiddle = Body.Find(Middle);
			const TArray<FVector>* TemplateMiddle = Template.Find(Middle);
			if (BodyMiddle && TemplateMiddle && BodyMiddle->Num() > 0 && TemplateMiddle->Num() > 0)
			{
				Compare(Arm.ToString() + TEXT(" hand"), ((*BodyMiddle)[0] - BodyArm->Last()).GetSafeNormal(),
					((*TemplateMiddle)[0] - TemplateArm->Last()).GetSafeNormal(), /*bJudged*/ false);
			}
		}
		const FName Leg(*FString::Printf(TEXT("%sLeg"), Side));
		const TArray<FVector>* BodyLeg = Body.Find(Leg);
		const TArray<FVector>* TemplateLeg = Template.Find(Leg);
		if (BodyLeg && TemplateLeg)
		{
			Compare(Leg.ToString() + TEXT(" thigh"), PoseDirectionAt(*BodyLeg, 0.25), PoseDirectionAt(*TemplateLeg, 0.25));
			Compare(Leg.ToString() + TEXT(" calf"), PoseDirectionAt(*BodyLeg, 0.75), PoseDirectionAt(*TemplateLeg, 0.75));
		}
	}
	// The shoulder and hip lines, right to left: a body facing another way, or with its sides swapped, turns them.
	Compare(TEXT("Shoulders (right to left)"), PoseSpan(Body, FName(TEXT("RightArm")), FName(TEXT("LeftArm"))),
		PoseSpan(Template, FName(TEXT("RightArm")), FName(TEXT("LeftArm"))));
	Compare(TEXT("Hips (right to left)"), PoseSpan(Body, FName(TEXT("RightLeg")), FName(TEXT("LeftLeg"))),
		PoseSpan(Template, FName(TEXT("RightLeg")), FName(TEXT("LeftLeg"))));
	return Out;
}

TArray<FMantleSecantTurn> FMantleMetaHumanPose::SecantAlign(const TArray<int32>& Parents, TArray<FVector>& InOutJoints, const TArray<FMantleSecantChain>& Chains, const int32 SkipBone)
{
	using namespace MantleMetaHumanPosePrivate;
	TArray<FMantleSecantTurn> Out;
	const int32 NumBones = FMath::Min(Parents.Num(), InOutJoints.Num());

	// Each bone's first chain (Epic's GetFirstChainMappingForBone) and its place there; a chain with a bone out of range is left.
	TArray<int32> ChainOf;
	TArray<int32> PlaceOf;
	ChainOf.Init(INDEX_NONE, NumBones);
	PlaceOf.Init(INDEX_NONE, NumBones);
	TArray<bool> Usable;
	Usable.Init(false, Chains.Num());
	for (int32 Chain = 0; Chain < Chains.Num(); ++Chain)
	{
		const TArray<int32>& Bones = Chains[Chain].Bones;
		Usable[Chain] = Bones.Num() > 0 && !Bones.ContainsByPredicate([NumBones](const int32 Bone) { return Bone < 0 || Bone >= NumBones; });
		for (int32 Place = 0; Usable[Chain] && Place < Bones.Num(); ++Place)
		{
			if (ChainOf[Bones[Place]] == INDEX_NONE)
			{
				ChainOf[Bones[Place]] = Chain;
				PlaceOf[Bones[Place]] = Place;
			}
		}
	}
	// Parameters by length: the target's from the joints as given (the turns never change a bone's length), the source's.
	TArray<TArray<double>> TargetParams;
	TArray<TArray<double>> SourceParams;
	for (int32 Chain = 0; Chain < Chains.Num(); ++Chain)
	{
		TArray<FVector> Joints;
		for (int32 Place = 0; Usable[Chain] && Place < Chains[Chain].Bones.Num(); ++Place)
		{
			Joints.Add(InOutJoints[Chains[Chain].Bones[Place]]);
		}
		TargetParams.Add(PoseChainParams(Joints));
		SourceParams.Add(PoseChainParams(Chains[Chain].Source));
	}
	auto FindChain = [&Chains, &Usable](const FName Name) -> int32
	{
		for (int32 Chain = 0; !Name.IsNone() && Chain < Chains.Num(); ++Chain)
		{
			if (Usable[Chain] && Chains[Chain].Name == Name)
			{
				return Chain;
			}
		}
		return INDEX_NONE;
	};
	const FName SpineName(TEXT("Spine"));
	const FName NeckName(TEXT("Neck"));
	const FName HeadName(TEXT("Head"));

	TArray<bool> Below;
	Below.Init(false, NumBones);
	for (int32 Bone = 0; Bone < NumBones; ++Bone)
	{
		const int32 ChainIndex = ChainOf[Bone];
		if (ChainIndex == INDEX_NONE || Bone == SkipBone || Chains[ChainIndex].Source.Num() == 0)
		{
			continue;
		}
		const FMantleSecantChain& Chain = Chains[ChainIndex];
		const int32 Place = PlaceOf[Bone];
		FVector Align;
		FVector Match;
		if (Place + 1 >= Chain.Bones.Num())
		{
			// The chain's last bone has no child in it: only a one-bone Spine or Neck is aimed, at the next chain's start.
			const FName NextName = Chain.Name == SpineName ? NeckName : Chain.Name == NeckName ? HeadName : FName();
			const int32 Next = FindChain(NextName);
			if (Chain.Bones.Num() != 1 || Next == INDEX_NONE || Chains[Next].Source.Num() == 0)
			{
				continue;
			}
			Align = PoseUnit(InOutJoints[Chains[Next].Bones[0]] - InOutJoints[Bone]);
			Match = PoseUnit(Chains[Next].Source[0] - PoseAtParam(Chain.Source, SourceParams[ChainIndex], 0.0));
		}
		else
		{
			// The bone's own segment against the source between the same two parameters.
			const TArray<double>& Params = TargetParams[ChainIndex];
			Align = PoseUnit(InOutJoints[Chain.Bones[Place + 1]] - InOutJoints[Bone]);
			Match = PoseUnit(PoseAtParam(Chain.Source, SourceParams[ChainIndex], Params[Place + 1]) - PoseAtParam(Chain.Source, SourceParams[ChainIndex], Params[Place]));
		}
		const FVector Axis = FVector::CrossProduct(Align, Match);
		if (Axis.Size() < 1e-9)
		{
			continue;
		}
		const double Angle = FMath::Acos(FMath::Clamp(FVector::DotProduct(Align, Match), -1.0, 1.0));
		FMantleSecantTurn& Turn = Out.AddDefaulted_GetRef();
		Turn.Bone = Bone;
		Turn.Rotation = FQuat(Axis.GetSafeNormal(), Angle);
		// Swing the bone's descendants about its joint (parents come before children).
		const FVector Pivot = InOutJoints[Bone];
		for (int32 Other = 0; Other < NumBones; ++Other)
		{
			Below[Other] = false;
		}
		Below[Bone] = true;
		for (int32 Other = Bone + 1; Other < NumBones; ++Other)
		{
			const int32 Parent = Parents[Other];
			if (Parent >= Bone && Parent < Other && Below[Parent])
			{
				Below[Other] = true;
				InOutJoints[Other] = Pivot + Turn.Rotation.RotateVector(InOutJoints[Other] - Pivot);
			}
		}
	}
	return Out;
}

TArray<FString> FMantleWholeBodyCheck::Missing() const
{
	TArray<FString> Out;
	if (!bChecked)
	{
		return Out;
	}
	if (!bHead)
	{
		Out.Add(TEXT("the head"));
	}
	if (!bLeftFoot && !bRightFoot)
	{
		Out.Add(TEXT("the legs and feet"));
	}
	else if (!bLeftFoot)
	{
		Out.Add(TEXT("the left leg and foot"));
	}
	else if (!bRightFoot)
	{
		Out.Add(TEXT("the right leg and foot"));
	}
	if (Out.Num() == 0 && !bSpan)
	{
		Out.Add(TEXT("part of the body between the feet and the head"));
	}
	return Out;
}

FMantleWholeBodyCheck FMantleMetaHumanPose::CheckWholeBody(const FBox3d& Kept, const FVector& Head, const FVector& LeftFoot, const FVector& RightFoot)
{
	FMantleWholeBodyCheck Out;
	const double Floor = FMath::Min(LeftFoot.Z, RightFoot.Z);
	Out.JointSpanCm = Head.Z - Floor;
	if (!FMath::IsFinite(Out.JointSpanCm) || Out.JointSpanCm <= 0.0)
	{
		return Out;
	}
	Out.bChecked = true;
	if (!Kept.IsValid)
	{
		return Out;
	}
	Out.KeptHeightCm = Kept.Max.Z - Kept.Min.Z;
	Out.CoveredCm = FMath::Max(0.0, FMath::Min(Kept.Max.Z, Head.Z) - FMath::Max(Kept.Min.Z, Floor));
	const double Reach = WholeBodyReach * Out.JointSpanCm;
	auto Near = [&Kept, Reach](const FVector& Joint)
	{
		return Kept.ComputeSquaredDistanceToPoint(Joint) <= Reach * Reach;
	};
	Out.bHead = Near(Head);
	Out.bLeftFoot = Near(LeftFoot);
	Out.bRightFoot = Near(RightFoot);
	Out.bSpan = Out.CoveredCm >= (1.0 - WholeBodyShortfall) * Out.JointSpanCm;
	Out.bNotTooTall = Out.KeptHeightCm <= WholeBodyMaxHeight * Out.JointSpanCm;
	return Out;
}

FString FMantleMetaHumanPose::WholeBodyMessage(const FMantleWholeBodyCheck& Check, TConstArrayView<FString> Suggested)
{
	const TArray<FString> Missing = Check.Missing();
	TArray<FString> Lines;
	Lines.Add(TEXT("The parts kept as bare skin aren't a whole body, so Convert stopped here (it won't stretch part of a body to full height)."));
	if (Missing.Num() > 0)
	{
		Lines.Add(FString::Printf(TEXT("Missing: %s."), *FString::Join(Missing, TEXT("; "))));
	}
	if (!Check.bNotTooTall)
	{
		Lines.Add(TEXT("Something much taller than the body is kept, such as a weapon, a staff or a tall hat."));
	}
	Lines.Add(FString::Printf(TEXT("The kept parts are %.0f cm tall and cover %.0f cm of the %.0f cm between the skeleton's feet and its head."),
		Check.KeptHeightCm, Check.CoveredCm, Check.JointSpanCm));
	if (Suggested.Num() > 0)
	{
		TArray<FString> Quoted;
		for (const FString& Slot : Suggested)
		{
			Quoted.Add(FString::Printf(TEXT("'%s'"), *Slot));
		}
		Lines.Add(FString::Printf(TEXT("Removed now, near the missing parts: %s."), *FString::Join(Quoted, TEXT(", "))));
	}
	Lines.Add(TEXT("Under Strip, untick the slots that hold the missing bare skin so they are kept, and tick clothing, weapon and prop slots so they are removed, then convert again. A character whose clothing has no skin under it can't become a MetaHuman."));
	return FString::Join(Lines, TEXT(" "));
}

bool FMantleMetaHumanPose::PoseIntoAPose(USkeletalMesh& Body, const FString& Folder, const FString& Tag, const double DefaultHeightCm,
	FMantleMetaHumanPoseResult& OutResult, FString& OutError)
{
	using namespace MantleMetaHumanPosePrivate;
	OutResult = FMantleMetaHumanPoseResult();
	USkeletalMesh* Template = LoadTemplateBody(OutError);
	if (!Template)
	{
		return false;
	}
	const FString Name = FMantleMetaHumanSteps::AssetTag(Tag);
	FAnimPose ClipPose;
	return PoseRetarget(Body, *Template, Folder, Name, ClipPose, OutResult, OutError)
		&& PoseFreeze(Body, Folder, Name, ClipPose, DefaultHeightCm, OutResult, OutError);
}

bool FMantleMetaHumanPoseFixer::IsBodyToConvert(const FMantleConvertContext& Context, const int32 PartIndex, const FMantleAvatarContract& Contract)
{
	using namespace MantleMetaHumanPosePrivate;
	if (Context.Route != EMantleAvatarRoute::Convert || !Context.AssemblyFolder.IsEmpty() || !Context.Parts.IsValidIndex(PartIndex))
	{
		return false;
	}
	const FMantleConvertPart& Part = Context.Parts[PartIndex];
	// A model with no skeleton is a body to convert too (its posed mesh comes from the MHUnrigged step, not this one).
	if (Part.bUnrigged)
	{
		return FMantleUnriggedBody::IsUnriggedBody(Context, PartIndex);
	}
	const USkeletalMesh* Original = Part.Original.IsValid() ? Part.Original.Get() : Part.Mesh.Get();
	return Original && Part.bIncluded && Part.Slot.Equals(PoseAvatarSlot, ESearchCase::CaseSensitive)
		&& FMantleCosmeticExport::FindReferenceLOD(Original, Contract) == INDEX_NONE;
}

void FMantleMetaHumanPoseFixer::Analyze(const FMantleConvertContext& Context, TArray<FMantleConvertFix>& OutFixes) const
{
	const FMantleAvatarContract* Contract = FMantleAvatarContract::Get();
	if (!Contract)
	{
		return;
	}
	for (int32 PartIndex = 0; PartIndex < Context.Parts.Num(); ++PartIndex)
	{
		// A model with no skeleton has nothing to pose: the MHUnrigged step bent its geometry instead.
		if (!IsBodyToConvert(Context, PartIndex, *Contract) || Context.Parts[PartIndex].bUnrigged)
		{
			continue;
		}
		// A face-only part has no body to pose (its head is conformed alone, onto MetaHuman's own body).
		if (const FMantleConvertMetaHumanWork* Work = Context.MetaHuman.Find(PartIndex); Work && Work->bFaceOnly)
		{
			continue;
		}
		FMantleConvertFix& Fix = OutFixes.AddDefaulted_GetRef();
		Fix.FixerId = GetId();
		Fix.PartIndex = PartIndex;
		Fix.Problem = TEXT("MetaHuman's conform fits a body best in MetaHuman's own A-pose");
		FString Error;
		if (!FMantleMetaHumanPose::LoadTemplateBody(Error))
		{
			Fix.Action = FString::Printf(TEXT("Can't: %s."), *Error);
			Fix.bCanFix = false;
			Fix.bEnabled = false;
			continue;
		}
		Fix.Action = TEXT("Poses the bare-skin body into MetaHuman's A-pose with Epic's IK Retargeter (it reads any bone names) and freezes that pose into a mesh, in the Work folder.");
	}
}

namespace MantleMetaHumanPosePrivate
{
	/**
	 * The slots Strip removed from the part's original that come near the joints a failed whole-body check missed (the
	 * bind pose, the original's own bounds and joints), largest first, at most four, never eyes, teeth, hair, weapons or
	 * props: what the creator most likely has to untick.
	 */
	TArray<FString> PoseSlotsNearMissing(const FMantleConvertContext& Context, const int32 PartIndex, const FMantleMetaHumanPoseResult& Result)
	{
		TArray<FString> Out;
		const FMantleWholeBodyCheck& Check = Result.WholeBody;
		USkeletalMesh* Original = Context.Parts.IsValidIndex(PartIndex) ? Context.Parts[PartIndex].Original.Get() : nullptr;
		const TSet<int32> Removed = Context.StripSlots.FindRef(PartIndex);
		if (!Original || Removed.Num() == 0 || !Check.bChecked)
		{
			return Out;
		}
		FMantleStripPlan Plan;
		FString Error;
		if (!FMantleAvatarStrip::Plan(*Original, &Removed, Plan, Error))
		{
			return Out;
		}
		const FReferenceSkeleton& Reference = Original->GetRefSkeleton();
		TArray<FTransform> Globals;
		PoseRetargetGlobals(Reference, Reference.GetRefBonePose(), Globals);
		auto JointOf = [&Reference, &Globals](const FName Bone, FVector& OutJoint)
		{
			const int32 Index = Reference.FindBoneIndex(Bone);
			if (!Globals.IsValidIndex(Index))
			{
				return false;
			}
			OutJoint = Globals[Index].GetLocation();
			return true;
		};
		const TArray<FName>* SpineChain = Result.Chains.Find(FName(TEXT("Spine")));
		const FName TopBone = !Result.HeadBone.IsNone() ? Result.HeadBone : (SpineChain && SpineChain->Num() > 0 ? SpineChain->Last() : FName());
		FVector Top;
		FVector LeftFoot;
		FVector RightFoot;
		if (!JointOf(TopBone, Top) || !JointOf(Result.LeftFootBone, LeftFoot) || !JointOf(Result.RightFootBone, RightFoot))
		{
			return Out;
		}
		const double Span = Top.Z - FMath::Min(LeftFoot.Z, RightFoot.Z);
		if (Span <= 0.0)
		{
			return Out;
		}
		TArray<FVector> Missed;
		if (!Check.bHead)
		{
			Missed.Add(Top);
		}
		if (!Check.bLeftFoot)
		{
			Missed.Add(LeftFoot);
		}
		if (!Check.bRightFoot)
		{
			Missed.Add(RightFoot);
		}
		const double Reach = FMantleMetaHumanPose::WholeBodyReach * Span;
		TArray<const FMantleStripSlot*> Near;
		for (const FMantleStripSlot& Slot : Plan.Slots)
		{
			FMantleOutfitSection Section;
			Section.SlotName = Slot.SlotName.ToString();
			Section.MaterialName = Slot.MaterialName;
			if (!Removed.Contains(Slot.Index) || FMantleAvatarStrip::NamesFaceDetail(Section.SlotName, Section.MaterialName) || FMantleOutfitSections::IsProp(Section))
			{
				continue;
			}
			for (const FVector& Joint : Missed)
			{
				if (Slot.Bounds.IsValid && Slot.Bounds.ComputeSquaredDistanceToPoint(Joint) <= Reach * Reach)
				{
					Near.Add(&Slot);
					break;
				}
			}
		}
		Near.StableSort([](const FMantleStripSlot& A, const FMantleStripSlot& B) { return A.Triangles > B.Triangles; });
		for (int32 Index = 0; Index < Near.Num() && Index < 4; ++Index)
		{
			Out.Add(Near[Index]->SlotName.ToString());
		}
		return Out;
	}
}

bool FMantleMetaHumanPoseFixer::Apply(const FMantleConvertFix& Fix, FMantleConvertContext& Context, FString& OutError) const
{
	if (Fix.FixerId != GetId() || !Context.Parts.IsValidIndex(Fix.PartIndex))
	{
		OutError = TEXT("the A-pose step names no part");
		return false;
	}
	FMantleConvertPart& Part = Context.Parts[Fix.PartIndex];
	USkeletalMesh* SkinOnly = Part.Mesh.Get();
	const bool bStripped = SkinOnly && SkinOnly != Part.Original.Get()
		&& Context.CreatedAssets.ContainsByPredicate([SkinOnly](const TWeakObjectPtr<UObject>& Created) { return Created.Get() == SkinOnly; });
	if (!bStripped)
	{
		OutError = TEXT("the body was not stripped to bare skin first (Strip's bare-skin line)");
		return false;
	}
	// Nothing of Epic's, MetaHuman Creator's or the source's may change (the retargeter's default ops included); the step
	// writes only into <output>/Work.
	const FString WorkFolder = Context.OutputFolder / TEXT("Work");
	const TArray<FString> Roots = FMantleMetaHumanSteps::ProtectedRoots(Context, Fix.PartIndex);
	const TSet<FString> DirtyBefore = FMantleMetaHumanSteps::DirtyUnder(Roots, WorkFolder);
	FMantleMetaHumanPoseResult Result;
	bool bPosed = FMantleMetaHumanPose::PoseIntoAPose(*SkinOnly, WorkFolder, Part.Name, FMantleAvatarHeight::TargetCm(), Result, OutError);
	if (!bPosed && !Result.WholeBody.Passes())
	{
		// Point at the slots the creator most likely has to untick.
		OutError = FMantleMetaHumanPose::WholeBodyMessage(Result.WholeBody, MantleMetaHumanPosePrivate::PoseSlotsNearMissing(Context, Fix.PartIndex, Result));
	}
	// Checked whether the step finished or not: one that stopped half-way may have changed something too.
	FString Dirtied;
	if (!FMantleMetaHumanSteps::CheckUnchanged(Roots, WorkFolder, DirtyBefore, TEXT("The A-pose step"), Dirtied))
	{
		OutError = bPosed ? Dirtied : FString::Printf(TEXT("%s. %s"), *OutError, *Dirtied);
		bPosed = false;
	}
	if (!bPosed)
	{
		// The fixer contract: a failed Apply leaves nothing behind and the context as it was.
		FMantleMetaHumanSteps::Discard(Result.Created);
		return false;
	}
	for (const TWeakObjectPtr<UObject>& Created : Result.Created)
	{
		Context.CreatedAssets.AddUnique(Created);
	}
	FMantleConvertMetaHumanWork& Work = Context.MetaHuman.FindOrAdd(Fix.PartIndex);
	Work.SkinOnly = SkinOnly;
	Work.TargetRig = Result.TargetRig;
	Work.APoseClip = Result.APoseClip;
	Work.PosedMesh = Result.PosedMesh;
	Work.HeadBone = Result.HeadBone;
	Work.HandBone = Result.HandBone;
	Work.HeadJoint = Result.HeadJoint;
	Work.InputScale = Result.InputScale;
	const UStaticMesh* Posed = Result.PosedMesh.Get();
	Context.Notes.Add(FString::Printf(TEXT("%s: posed into MetaHuman's A-pose (%d chains, within %.1f degrees of it; hand %s moved %.1f cm%s) as %s, scaled by %.4f from %.1f cm toward the default height."),
		*Part.Name, Result.Chains.Num(), Result.PoseCheck.WorstDegrees(), *Result.HandBone.ToString(), Result.HandMovedCm,
		Result.bAlreadyInAPose ? TEXT(", it was already in the A-pose") : TEXT(""), Posed ? *Posed->GetName() : TEXT("?"), Result.InputScale, Result.PosedHeightCm));
	return true;
}

