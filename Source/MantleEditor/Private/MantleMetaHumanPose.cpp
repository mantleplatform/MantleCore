void FMantleMetaHumanSteps::Discard(TArray<TWeakObjectPtr<UObject>>& Made)
{
	TArray<UObject*> Doomed;
	for (const TWeakObjectPtr<UObject>& Object : Made)
	{
		if (UObject* Asset = Object.Get())
		{
			Asset->GetOutermost()->ClearDirtyFlag();
			Doomed.AddUnique(Asset);
		}
	}
	Made.Reset();
	if (Doomed.Num() > 0)
	{
		const int32 Deleted = FMantleAssetCleanup::MoveAside(Doomed);
		UE_LOG(LogMantle, Log, TEXT("MANTLE_CONVERT discarded %d of %d assets a failed MetaHuman step made"), Deleted, Doomed.Num());
	}
}

TArray<FString> FMantleMetaHumanSteps::ProtectedRoots(const FMantleConvertContext& Context, const int32 PartIndex)
{
	TArray<FString> Out = { TEXT("/Engine/"), TEXT("/MetaHumanCharacter/") };
	auto AddFolderOf = [&Out](const UObject* Object)
	{
		if (Object)
		{
			Out.AddUnique(FPackageName::GetLongPackagePath(Object->GetOutermost()->GetName()) + TEXT("/"));
		}
	};
	auto AddMeshOf = [&AddFolderOf](const USkeletalMesh* Mesh)
	{
		if (Mesh)
		{
			AddFolderOf(Mesh);
			AddFolderOf(Mesh->GetSkeleton());
			AddFolderOf(Mesh->GetPhysicsAsset());
		}
	};
	if (Context.Parts.IsValidIndex(PartIndex))
	{
		AddMeshOf(Context.Parts[PartIndex].Original.Get());
		// The skin-only copy shares the source's skeleton: only its own package is the step's to write.
		const USkeletalMesh* Current = Context.Parts[PartIndex].Mesh.Get();
		if (Current)
		{
			AddFolderOf(Current->GetSkeleton());
			AddFolderOf(Current->GetPhysicsAsset());
		}
	}
	AddFolderOf(Context.Source.Get());
	return Out;
}

TSet<FString> FMantleMetaHumanSteps::DirtyUnder(TConstArrayView<FString> Roots, const FString& Except)
{
	const FString ExceptFolder = Except.IsEmpty() || Except.EndsWith(TEXT("/")) ? Except : Except + TEXT("/");
	// /Engine/Transient and the packages inside it (Epic's build makes /Engine/Transient/Body_7 and the like) are never saved.
	const FString Transient = GetTransientPackage()->GetName();
	const FString InsideTransient = Transient + TEXT("/");
	TSet<FString> Out;
	for (TObjectIterator<UPackage> It; It; ++It)
	{
		if (!It->IsDirty())
		{
			continue;
		}
		const FString Name = It->GetName();
		if (Name.Equals(Transient) || Name.StartsWith(InsideTransient) || (!ExceptFolder.IsEmpty() && Name.StartsWith(ExceptFolder)))
		{
			continue;
		}
		for (const FString& Root : Roots)
		{
			if (Name.StartsWith(Root))
			{
				Out.Add(Name);
				break;
			}
		}
	}
	return Out;
}

bool FMantleMetaHumanSteps::CheckUnchanged(TConstArrayView<FString> Roots, const FString& Except, const TSet<FString>& DirtyBefore, const TCHAR* Step, FString& OutError)
{
	TArray<FString> Dirtied;
	for (const FString& Name : DirtyUnder(Roots, Except))
	{
		if (!DirtyBefore.Contains(Name))
		{
			Dirtied.Add(Name);
		}
	}
	if (Dirtied.Num() == 0)
	{
		return true;
	}
	Dirtied.Sort();
	OutError = FString::Printf(TEXT("%s changed packages it must never change (%s); nothing it made is kept. Don't save those packages."), Step,
		*FString::Join(Dirtied, TEXT(", ")));
	UE_LOG(LogMantle, Warning, TEXT("MANTLE_CONVERT %s"), *OutError);
	return false;
}

USkeletalMesh* FMantleMetaHumanPose::LoadTemplateBody(FString& OutError)
{
	USkeletalMesh* Template = FPackageName::DoesPackageExist(FPackageName::ObjectPathToPackageName(FString(TemplateBodyPath)))
		? LoadObject<USkeletalMesh>(nullptr, TemplateBodyPath)
		: nullptr;
	if (!Template)
	{
		OutError = TEXT("MetaHuman Creator's template body (SKM_Body) is missing: enable the MetaHuman Creator plugin");
	}
	return Template;
}

TArray<FMantleNamedChain> FMantleMetaHumanPose::VRoidChains(const TConstArrayView<FName> Names, FName& OutPelvis)
{
	OutPelvis = NAME_None;
	auto Find = [Names](const FString& Suffix)
	{
		for (const FName& Name : Names)
		{
			if (Name.ToString().EndsWith(Suffix, ESearchCase::IgnoreCase))
			{
				return Name;
			}
		}
		return FName();
	};
	const FName Hips = Find(TEXT("J_Bip_C_Hips"));
	const FName Spine = Find(TEXT("J_Bip_C_Spine"));
	const FName Head = Find(TEXT("J_Bip_C_Head"));
	if (Hips.IsNone() || Spine.IsNone() || Head.IsNone())
	{
		return {};
	}
	TArray<FMantleNamedChain> Out;
	// The spine runs to the highest chest bone VRoid exported (UpperChest is optional in VRM).
	FName SpineEnd = Find(TEXT("J_Bip_C_UpperChest"));
	SpineEnd = SpineEnd.IsNone() ? Find(TEXT("J_Bip_C_Chest")) : SpineEnd;
	Out.Add({ FName(TEXT("Spine")), Spine, SpineEnd.IsNone() ? Spine : SpineEnd });
	if (const FName Neck = Find(TEXT("J_Bip_C_Neck")); !Neck.IsNone())
	{
		Out.Add({ FName(TEXT("Neck")), Neck, Neck });
	}
	Out.Add({ FName(TEXT("Head")), Head, Head });
	for (const bool bLeft : { true, false })
	{
		const FString Side = bLeft ? TEXT("Left") : TEXT("Right");
		const FString Bip = bLeft ? TEXT("J_Bip_L_") : TEXT("J_Bip_R_");
		const FName UpperArm = Find(Bip + TEXT("UpperArm"));
		const FName Hand = Find(Bip + TEXT("Hand"));
		const FName UpperLeg = Find(Bip + TEXT("UpperLeg"));
		const FName Foot = Find(Bip + TEXT("Foot"));
		if (UpperArm.IsNone() || Hand.IsNone() || UpperLeg.IsNone() || Foot.IsNone())
		{
			return {};
		}
		Out.Add({ FName(Side + TEXT("Leg")), UpperLeg, Foot });
		if (const FName Toe = Find(Bip + TEXT("ToeBase")); !Toe.IsNone())
		{
			Out.Add({ FName(Side + TEXT("Foot")), Toe, Toe });
		}
		if (const FName Shoulder = Find(Bip + TEXT("Shoulder")); !Shoulder.IsNone())
		{
			Out.Add({ FName(Side + TEXT("Clavicle")), Shoulder, Shoulder });
		}
		Out.Add({ FName(Side + TEXT("Arm")), UpperArm, Hand });
		// VRoid's fingers are <Finger>1..3; its little finger is Epic's pinky.
		static const TPair<const TCHAR*, const TCHAR*> Fingers[] = { { TEXT("Thumb"), TEXT("Thumb") }, { TEXT("Index"), TEXT("Index") },
			{ TEXT("Middle"), TEXT("Middle") }, { TEXT("Ring"), TEXT("Ring") }, { TEXT("Little"), TEXT("Pinky") } };
		for (const TPair<const TCHAR*, const TCHAR*>& Finger : Fingers)
		{
			const FName First = Find(Bip + Finger.Key + TEXT("1"));
			const FName Last = Find(Bip + Finger.Key + TEXT("3"));
			if (!First.IsNone() && !Last.IsNone())
			{
				Out.Add({ FName(Side + Finger.Value), First, Last });
			}
		}
	}
	OutPelvis = Hips;
	return Out;
}

TMap<FName, TArray<FName>> FMantleMetaHumanPose::RigChainBones(const UObject& Rig, const USkeletalMesh& Mesh)
{
	TMap<FName, TArray<FName>> Out;
	const UIKRigDefinition* Definition = Cast<UIKRigDefinition>(&Rig);
	const UIKRigController* Controller = Definition ? UIKRigController::GetController(Definition) : nullptr;
	if (!Controller)
	{
		return Out;
	}
	const FReferenceSkeleton& Reference = Mesh.GetRefSkeleton();
	for (const FBoneChain& Chain : Controller->GetRetargetChains())
	{
		const int32 Start = Reference.FindBoneIndex(Controller->GetRetargetChainStartBone(Chain.ChainName));
		const int32 End = Reference.FindBoneIndex(Controller->GetRetargetChainEndBone(Chain.ChainName));
		if (Start == INDEX_NONE || End == INDEX_NONE)
		{
			continue;
		}
		TArray<FName> Path;
		int32 At = End;
		for (int32 Guard = 0; At != INDEX_NONE && Guard < 1024; ++Guard)
		{
			Path.Insert(Reference.GetBoneName(At), 0);
			if (At == Start)
			{
				break;
			}
			At = Reference.GetParentIndex(At);
		}
		if (At == Start)
		{
			Out.Add(Chain.ChainName, MoveTemp(Path));
		}
	}
	return Out;
}

